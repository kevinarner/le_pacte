import 'package:flutter_test/flutter_test.dart';
import 'package:le_pacte/utils/telephone.dart';

/// Mêmes cas, à l'identique, que les vecteurs de test de
/// `normaliser_telephone()` (telephones_phase1.sql / phase2) : la base et
/// l'app doivent toujours donner la même forme canonique.
void main() {
  const cas = <(String, String?)>[
    ('06 70 41 92 77', '+33670419277'),
    ('0670419277', '+33670419277'),
    ('+33 6 70 41 92 77', '+33670419277'),
    ('+33670419277', '+33670419277'),
    ('0033 6 70 41 92 77', '+33670419277'),
    ('+33 (0)6 70 41 92 77', '+33670419277'),
    ('06.70.41.92.77', '+33670419277'),
    ('06-70-41-92-77', '+33670419277'),
    ('06\u00a070\u00a041 92 77', '+33670419277'),
    ('  06 70 41 92 77  ', '+33670419277'),
    ('+33\u202f6\u202f70\u202f41 92 77', '+33670419277'),
    ('06\u201170\u201341 92 77', '+33670419277'),
    ('06\u000970 41 92 77', '+33670419277'),
    ('07 81 22 33 44', '+33781223344'),
    ('0692 12 34 56', '+262692123456'),
    ('+262 692 12 34 56', '+262692123456'),
    ('+33 692 12 34 56', '+262692123456'),
    ('+262 (0)692 12 34 56', '+262692123456'),
    ('0693 12 34 56', '+262693123456'),
    ('0639 12 34 56', '+262639123456'),
    ('0690 12 34 56', '+590690123456'),
    ('0691 12 34 56', '+590691123456'),
    ('0694 12 34 56', '+594694123456'),
    ('0696 12 34 56', '+596696123456'),
    ('0697 12 34 56', '+596697123456'),
    ('+44 7911 123456', '+447911123456'),
    ('0044 7911 123456', '+447911123456'),
    ('+1 202 555 0143', '+12025550143'),
    ('0000', null),
    ('00', null),
    ('t', null),
    ('', null),
    ('01 23 45 67 89', null),
    ('+33 1 23 45 67 89', null),
    ('09 70 00 00 00', null),
    ('6 70 41 92 77', null),
    ('07911 123456', null),
    ('+33 12345', null),
    ('+262 262 12 34 56', null),
    ('0692 12 34', null),
    ('06 70 41 92 77 8', null),
    ('+33 6 70 41 92 7a', null),
  ];

  for (final (saisie, attendu) in cas) {
    test('normaliserTelephone("$saisie") = $attendu', () {
      expect(normaliserTelephone(saisie), attendu);
    });
  }

  test('null reste null', () => expect(normaliserTelephone(null), isNull));

  test('affichage', () {
    expect(formaterTelephone('+33670419277'), '06 70 41 92 77');
    expect(formaterTelephone('0692123456'), '0692 12 34 56');
    expect(formaterTelephone('+44 7911 123456'), '+447911123456');
    expect(formaterTelephone('0000'), '0000');
  });
}
